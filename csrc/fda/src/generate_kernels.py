# dtype) to compile them in parallel. The diffusion mask replaces the causal flag.

import argparse
import itertools
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional

DTYPE_MAP = {
    "fp16": "cutlass::half_t",
    "bf16": "cutlass::bfloat16_t",
}

SM = [80]  # Sm80 kernels support up to
HEAD_DIMENSIONS = [32, 64, 96, 128, 192, 256]
NAMESPACE_INCLUDE = '#include "namespace_config.h"\n'


def get_fwd_template() -> str:
    return NAMESPACE_INCLUDE + """#include "flash_fwd_launch_template.h"

namespace FLASH_NAMESPACE {{

template<>
void run_mha_fwd_<{DTYPE}, {HEAD_DIM}>(Flash_fwd_params &params, cudaStream_t stream) {{
#ifdef FDA_TUNING
    // Tuning builds: FDA_TUNE_FWD=<i> runs candidate i of tuning.h instead of the dispatch
    if (run_mha_fwd_tuning<{HEAD_DIM}, {DTYPE}>(params, stream)) {{ return; }}
#endif
    run_mha_fwd_hdim{HEAD_DIM}<{DTYPE}>(params, stream);
}}

}} // namespace FLASH_NAMESPACE
"""


def get_fwd_split_template() -> str:
    return NAMESPACE_INCLUDE + """#include "flash_fwd_launch_template.h"

namespace FLASH_NAMESPACE {{

template void run_mha_fwd_splitkv_dispatch<{DTYPE}, {HEAD_DIM}>(Flash_fwd_params &params, cudaStream_t stream);

}} // namespace FLASH_NAMESPACE
"""


def get_bwd_template() -> str:
    return NAMESPACE_INCLUDE + """#include "flash_bwd_launch_template.h"

namespace FLASH_NAMESPACE {{

template<>
void run_mha_bwd_<{DTYPE}, {HEAD_DIM}>(Flash_bwd_params &params, cudaStream_t stream) {{
#ifdef FDA_TUNING
    // Tuning builds: FDA_TUNE_BWD=<i> runs candidate i of tuning.h instead of the dispatch
    if (run_mha_bwd_tuning<{HEAD_DIM}, {DTYPE}>(params, stream)) {{ return; }}
#endif
    run_mha_bwd_hdim{HEAD_DIM}<{DTYPE}>(params, stream);
}}

}} // namespace FLASH_NAMESPACE
"""


# Tuning builds (FDA_TUNING=1): one file per candidate configuration of tuning.h, compiled in parallel
NUM_TUNING_CANDIDATES = {"fwd": 19, "bwd": 25}


def get_tune_template(direction: str) -> str:
    return NAMESPACE_INCLUDE + f"""#define FDA_TUNING_{direction.upper()}_CANDIDATES
#include "flash_{direction}_launch_template.h"
#include "tuning_candidates.h"

namespace FLASH_NAMESPACE {{{{

template void run_mha_{direction}_candidate<{{DTYPE}}, {{HEAD_DIM}}, {{CANDIDATE}}>(Flash_{direction}_params &params, cudaStream_t stream);

}}}} // namespace FLASH_NAMESPACE
"""


@dataclass
class TuningKernel:
    sm: int
    dtype: str
    head_dim: int
    direction: str
    candidate: int

    @property
    def template(self) -> str:
        return get_tune_template(self.direction).format(
            DTYPE=DTYPE_MAP[self.dtype], HEAD_DIM=self.head_dim, CANDIDATE=self.candidate)

    @property
    def filename(self) -> str:
        return f"flash_{self.direction}_hdim{self.head_dim}_{self.dtype}_tune{self.candidate}_sm{self.sm}.cu"


@dataclass
class Kernel:
    sm: int
    dtype: str
    head_dim: int
    direction: str

    @property
    def template(self) -> str:
        template_funcs = {
            "fwd": get_fwd_template,
            "fwd_split": get_fwd_split_template,
            "bwd": get_bwd_template,
        }
        return template_funcs[self.direction]().format(DTYPE=DTYPE_MAP[self.dtype], HEAD_DIM=self.head_dim)

    @property
    def filename(self) -> str:
        return f"flash_{self.direction}_hdim{self.head_dim}_{self.dtype}_sm{self.sm}.cu"


def get_all_kernels() -> List[Kernel]:
    for direction in ["fwd", "fwd_split", "bwd"]:
        for dtype, head_dim, sm in itertools.product(DTYPE_MAP.keys(), HEAD_DIMENSIONS, SM):
            yield Kernel(sm=sm, dtype=dtype, head_dim=head_dim, direction=direction)
            for candidate in range(NUM_TUNING_CANDIDATES.get(direction, 0)):
                yield TuningKernel(sm=sm, dtype=dtype, head_dim=head_dim, direction=direction, candidate=candidate)


def write_kernel(kernel: Kernel, autogen_dir: Path) -> None:
    prelude = """// Copyright (c) 2024, Tri Dao.
// Copyright (c) 2026, fast-diffusion-attention authors.
// Splitting the different head dimensions to different files to speed up compilation.
// This file is auto-generated. See "generate_kernels.py"\n"""
    content = prelude + kernel.template
    # Tuning candidates in a subdirectory (not committed, generated by setup.py)
    if isinstance(kernel, TuningKernel):
        autogen_dir = autogen_dir / "tuning"
        autogen_dir.mkdir(exist_ok=True)
    path = autogen_dir / kernel.filename
    # Keep unchanged files untouched (no spurious rebuilds)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main(output_dir: Optional[str]) -> None:
    if output_dir is None:
        output_dir = Path(__file__).parent
    else:
        output_dir = Path(output_dir)

    for kernel in get_all_kernels():
        write_kernel(kernel, output_dir)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        prog="generate_kernels",
        description="Generate the fast-diffusion-attention kernels template instantiations",
    )
    parser.add_argument(
        "-o",
        "--output_dir",
        required=False,
        help="Where to generate the kernels "
        " will default to the current directory ",
    )
    args = parser.parse_args()
    main(args.output_dir)
