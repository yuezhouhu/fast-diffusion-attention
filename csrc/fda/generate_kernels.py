from pathlib import Path

HDIMS = [64, 96, 128, 192, 256]
DTYPES_FWD = {"bf16": "cutlass::bfloat16_t", "fp16": "cutlass::half_t", "e4m3": "cutlass::float_e4m3_t"}
DTYPES_BWD = {"bf16": "cutlass::bfloat16_t", "fp16": "cutlass::half_t"}
SOFTCAPS = {"": "false", "_softcap": "true"}

HEADER = "// Copyright (c) 2026, fast-diffusion-attention authors.\n// Generated by csrc/fda/generate_kernels.py, do not edit.\n\n"


def guard(hdim, dtype, softcap):
    conds = [f"!defined(FLASHATTENTION_DISABLE_HDIM{hdim})"]
    if dtype == "fp16":
        conds.append("!defined(FLASHATTENTION_DISABLE_FP16)")
    if dtype == "e4m3":
        conds.append("!defined(FLASHATTENTION_DISABLE_FP8)")
    if softcap:
        conds.append("!defined(FLASHATTENTION_DISABLE_SOFTCAP)")
    return " && ".join(conds)


def file_name(direction, hdim, dtype, softcap):
    return f"flash_{direction}_hdim{hdim}_{dtype}{softcap}_sm90.cu"


def write_if_changed(path, src):
    # Keep the modification time of unchanged files, so that incremental builds do not recompile them
    if not path.exists() or path.read_text() != src:
        path.write_text(src)


def main():
    out_dir = Path(__file__).resolve().parent / "instantiations"
    out_dir.mkdir(exist_ok=True)
    for hdim in HDIMS:
        for dtype, ctype in DTYPES_FWD.items():
            for softcap, flag in SOFTCAPS.items():
                src = (HEADER + '#include "flash_fwd_launch_template.h"\n\n'
                       f"#if {guard(hdim, dtype, softcap)}\n"
                       f"template void run_mha_fwd_<90, {ctype}, {hdim}, {flag}>(Flash_fwd_params &params, cudaStream_t stream);\n"
                       "#endif\n")
                write_if_changed(out_dir / file_name("fwd", hdim, dtype, softcap), src)
        for dtype, ctype in DTYPES_BWD.items():
            for softcap, flag in SOFTCAPS.items():
                src = (HEADER + '#include "flash_bwd_launch_template.h"\n\n'
                       f"#if {guard(hdim, dtype, softcap)} && !defined(FLASHATTENTION_DISABLE_BACKWARD)\n"
                       f"template<>\nvoid run_mha_bwd_<90, {ctype}, {hdim}, {flag}>(Flash_bwd_params &params, cudaStream_t stream) {{\n"
                       f"    run_mha_bwd_hdim{hdim}<90, {ctype}, {flag}>(params, stream);\n"
                       "}\n#endif\n")
                write_if_changed(out_dir / file_name("bwd", hdim, dtype, softcap), src)


if __name__ == "__main__":
    main()
